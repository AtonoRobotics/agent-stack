def urdf_consolidation(
    source_urdfs: list[str] | None = None,
    output_name: str = "cr10_canonical",
) -> str:
    """Generate a script to consolidate multiple URDF files into one canonical version."""
    if source_urdfs is None:
        source_urdfs = [
            "~/dobot_cr10/cr10_robot.urdf",
            "~/dobot-cr10-stack/ros2/dobot_cr10_driver/urdf/dobot_cr10.urdf",
            "~/dobot_cr10/urdf/dobot_cr10.urdf",
        ]
    sources_str = ",\n        ".join(f'"{s}"' for s in source_urdfs)
    return textwrap.dedent(f"""\
    #!/usr/bin/env python3
    \"\"\"URDF consolidation script for CR10.

    Reads multiple URDF sources, compares joint limits, inertials, and meshes,
    then produces a canonical URDF combining the best from each.

    Generated by skills/robotics.py
    \"\"\"

    import os
    import xml.etree.ElementTree as ET
    from dataclasses import dataclass

    SOURCES = [
        {sources_str}
    ]
    OUTPUT = os.path.expanduser("~/dobot_cr10/{output_name}.urdf")


    @dataclass
    class JointInfo:
        name: str
        type: str
        lower: float
        upper: float
        velocity: float
        effort: float
        source: str


    def parse_joints(urdf_path: str) -> list[JointInfo]:
        tree = ET.parse(os.path.expanduser(urdf_path))
        root = tree.getroot()
        joints = []
        for j in root.findall("joint"):
            limit = j.find("limit")
            if limit is None:
                continue
            joints.append(JointInfo(
                name=j.get("name"),
                type=j.get("type"),
                lower=float(limit.get("lower", 0)),
                upper=float(limit.get("upper", 0)),
                velocity=float(limit.get("velocity", 0)),
                effort=float(limit.get("effort", 0)),
                source=urdf_path,
            ))
        return joints


    def compare_sources():
        print("# URDF Comparison Report")
        for path in SOURCES:
            expanded = os.path.expanduser(path)
            if not os.path.exists(expanded):
                print(f"  MISSING: {{path}}")
                continue
            joints = parse_joints(path)
            print(f"\\n## {{path}}")
            for j in joints:
                print(f"  {{j.name}} ({{j.type}}): "
                      f"[{{j.lower:.4f}}, {{j.upper:.4f}}] "
                      f"vel={{j.velocity}} effort={{j.effort}}")


    if __name__ == "__main__":
        compare_sources()
    """)



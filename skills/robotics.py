def isaac_sim_scene(
    robot_urdf: str = "~/dobot_cr10/cr10_robot.urdf",
    scene_name: str = "cr10_workspace",
    ground_plane: bool = True,
    lighting: str = "dome",
) -> str:
    """Generate an Isaac Sim Python scene script for the CR10 robot."""
    return textwrap.dedent(f"""\
    #!/usr/bin/env python3
    \"\"\"Isaac Sim scene: {scene_name}

    Loads the CR10 robot and workspace in Isaac Sim.
    Run inside the Isaac Sim Python environment:
        /workspace/isaaclab/_isaac_sim/python.sh {scene_name}.py

    Generated by skills/robotics.py
    \"\"\"

    from isaacsim import SimulationApp
    simulation_app = SimulationApp({{"headless": False}})

    import omni.isaac.core.utils.stage as stage_utils
    from omni.isaac.core import World
    from omni.isaac.core.robots import Robot
    from omni.isaac.core.utils.prims import create_prim
    from pxr import UsdPhysics, Gf

    world = World(stage_units_in_meters=1.0)
    scene = world.scene

    # Ground plane
    {"scene.add_ground_plane()" if ground_plane else "# No ground plane"}

    # Lighting
    create_prim(
        "/World/Light",
        "DomeLight" if "{lighting}" == "dome" else "DistantLight",
        attributes={{"intensity": 1000.0}},
    )

    # Load CR10 robot from URDF
    from omni.isaac.urdf import _urdf
    urdf_interface = _urdf.acquire_urdf_interface()
    import_config = _urdf.ImportConfig()
    import_config.merge_fixed_joints = False
    import_config.fix_base = True
    import_config.make_default_prim = True

    result = urdf_interface.parse_urdf("{robot_urdf}", import_config)
    urdf_interface.import_robot(
        "{robot_urdf}",
        result,
        import_config,
        "/World/CR10",
    )

    robot = scene.add(Robot(prim_path="/World/CR10", name="cr10"))

    # Physics
    world.reset()

    print(f"Scene '{scene_name}' loaded with CR10 robot")
    print(f"Robot DOF: {{robot.num_dof}}")
    print(f"Joint names: {{robot.dof_names}}")

    # Simulation loop
    while simulation_app.is_running():
        world.step(render=True)

    simulation_app.close()
    """)



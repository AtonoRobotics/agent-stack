def ros2_launch(
    package: str = "dobot_cr10_driver",
    node_name: str = "cr10_driver",
    robot_ip: str = "192.168.5.1",
    use_sim: bool = False,
) -> str:
    """Generate a ROS2 launch file for the CR10 driver or simulation bridge."""
    sim_param = "true" if use_sim else "false"
    return textwrap.dedent(f"""\
    # ROS2 launch file for {package}
    # Generated by skills/robotics.py

    from launch import LaunchDescription
    from launch.actions import DeclareLaunchArgument
    from launch.substitutions import LaunchConfiguration
    from launch_ros.actions import Node


    def generate_launch_description():
        return LaunchDescription([
            DeclareLaunchArgument("robot_ip", default_value="{robot_ip}"),
            DeclareLaunchArgument("use_sim", default_value="{sim_param}"),

            Node(
                package="{package}",
                executable="{node_name}",
                name="{node_name}",
                parameters=[{{
                    "robot_ip": LaunchConfiguration("robot_ip"),
                    "use_sim": LaunchConfiguration("use_sim"),
                    "dashboard_port": 29999,
                    "control_port": 30003,
                    "feedback_port": 30004,
                    "publish_rate": 100.0,
                }}],
                output="screen",
            ),
        ])
    """)

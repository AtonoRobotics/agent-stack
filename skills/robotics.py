def trajectory_smoothing(
    waypoints: list[list[float]] | None = None,
    dt: float = 0.01,
    max_velocity: float = 2.0,
    max_acceleration: float = 10.0,
    max_jerk: float = 500.0,
) -> str:
    """Generate a Python script for cuRobo trajectory smoothing on spline waypoints."""
    if waypoints is None:
        waypoints = [
            [0.0, -1.5708, 1.5708, 0.0, 1.5708, 0.0],
            [0.5, -1.2, 1.3, 0.2, 1.5, 0.1],
        ]
    wp_str = ",\n        ".join(str(w) for w in waypoints)
    return textwrap.dedent(f"""\
    #!/usr/bin/env python3
    \"\"\"cuRobo trajectory smoothing for CR10 spline paths.

    Pipeline: Cinema motion software -> Spline path -> cuRobo (smooth/validate)
              -> Joint trajectory -> Safety system -> Robot driver

    Generated by skills/robotics.py
    \"\"\"

    import torch
    import numpy as np
    from curobo.types.robot import JointState
    from curobo.wrap.reacher.motion_gen import MotionGen, MotionGenConfig

    WAYPOINTS = [
        {wp_str}
    ]
    DT = {dt}
    MAX_VELOCITY = {max_velocity}
    MAX_ACCELERATION = {max_acceleration}
    MAX_JERK = {max_jerk}


    def smooth_trajectory(waypoints, dt=DT):
        \"\"\"Smooth a spline trajectory through cuRobo's trajectory optimizer.\"\"\"
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

        # Load cuRobo config
        config = MotionGenConfig.load_from_robot_config(
            robot_cfg_path="config/cr10_curobo.yaml",
            world_cfg_path="config/cr10_world.yaml",
        )
        motion_gen = MotionGen(config)
        motion_gen.warmup()

        # Convert waypoints to joint states
        positions = torch.tensor(waypoints, device=device, dtype=torch.float32)

        # Use cuRobo to smooth — validates jerk/acceleration limits
        result = motion_gen.plan_batch(
            start_state=JointState(position=positions[:-1]),
            goal_state=JointState(position=positions[1:]),
        )

        if result.success.all():
            smoothed = result.get_interpolated_plan()
            print(f"Smoothed {{len(waypoints)}} waypoints -> {{smoothed.shape[0]}} points")
            print(f"Max velocity: {{smoothed.velocity.abs().max():.3f}} rad/s")
            print(f"Max acceleration: {{smoothed.acceleration.abs().max():.3f}} rad/s²")
            print(f"Max jerk: {{smoothed.jerk.abs().max():.3f}} rad/s³")
            return smoothed
        else:
            print(f"Smoothing failed for {{(~result.success).sum()}} segments")
            return None


    if __name__ == "__main__":
        smooth_trajectory(WAYPOINTS)
    """)


